//! Recording after a replayed prompt prefix.
//!
//! The chat stream replays a prompt prefix (Gemma 4's `<|channel>thought\n`,
//! or any leading part of it) through `parse_into`, then turns recording on, so
//! offsets count the generated text only. A prefix shorter than the whole header
//! leaves prompt bytes held: `<|channel>t` holds `t`, and when the output
//! `Answer` disproves the label, the parser releases `tAn` as reasoning. Even a
//! bare `<|channel>` is held, and surfaces as text inside a quote or on `reset`.
//! A prompt byte has no source in the generated text, so recording must refuse
//! there, before any generated byte. With nothing held, it records, and every
//! range reads back its own text from the generated input.

use std::ops::Range;

use dynamo_parsers_v2::{
    UnifiedParser, UnifiedParserEvent, UnifiedParserInit, UnifiedParserOutput,
    UnifiedParserStartingState, create_unified_parser_for_family,
};

const HEADER: &str = "<|channel>thought\n";

fn parser(prefix: &str, starting_state: UnifiedParserStartingState) -> Box<dyn UnifiedParser> {
    let mut parser = create_unified_parser_for_family("gemma4", &[]).unwrap();
    parser
        .initialize_request(UnifiedParserInit {
            starting_state,
            ..UnifiedParserInit::default()
        })
        .unwrap();
    let mut output = UnifiedParserOutput::default();
    parser.parse_into(prefix, &mut output).unwrap();
    assert!(
        output.events.is_empty(),
        "the prefix {prefix:?} emitted {:?}",
        output.events
    );
    parser
}

fn text(event: &UnifiedParserEvent) -> Option<&str> {
    match event {
        UnifiedParserEvent::Text(text) | UnifiedParserEvent::Reasoning(text) => Some(text),
        _ => None,
    }
}

/// Feeds `chunks` and finishes; returns the emitted text and its ranges.
fn run(
    parser: &mut Box<dyn UnifiedParser>,
    chunks: &[&str],
) -> (Vec<UnifiedParserEvent>, Vec<Range<usize>>) {
    let mut events = Vec::new();
    let mut ranges = Vec::new();
    for chunk in chunks {
        let mut output = UnifiedParserOutput::default();
        parser.parse_into(chunk, &mut output).unwrap();
        events.extend(output.events);
        parser.take_sources(&mut ranges);
    }
    events.extend(parser.finish().unwrap().events);
    parser.take_sources(&mut ranges);
    (events, ranges)
}

#[test]
fn recording_after_the_prefix_refuses_held_prompt_bytes() {
    // The chat stream replays a prefix in the Reasoning starting state.
    let states = [
        UnifiedParserStartingState::None,
        UnifiedParserStartingState::Reasoning,
    ];
    for (state, output) in states.into_iter().flat_map(|state| {
        ["Answer only.", "\ndeep thought<channel|>Answer.", ""].map(|o| (state, o))
    }) {
        let chunks: Vec<String> = output.chars().map(String::from).collect();
        let chunks: Vec<&str> = chunks.iter().map(String::as_str).collect();
        for end in "<|channel>".len()..=HEADER.len() {
            let prefix = &HEADER[..end];
            let label = format!("{state:?}, prefix {prefix:?}, output {output:?}");
            let (stock, _) = run(&mut parser(prefix, state), &chunks);
            let mut recording = parser(prefix, state);
            let held = end < HEADER.len();
            assert_eq!(recording.record_sources(), !held, "{label}: record_sources");
            let (events, ranges) = run(&mut recording, &chunks);
            assert_eq!(events, stock, "{label}: recording changed the events");
            if held {
                assert!(
                    ranges.is_empty(),
                    "{label}: a refused recording gave ranges"
                );
                continue;
            }
            let emitted: String = events.iter().filter_map(text).collect();
            let read: String = ranges.iter().map(|range| &output[range.clone()]).collect();
            assert_eq!(
                read, emitted,
                "{label}: the ranges do not read back the text"
            );
        }
    }
}
